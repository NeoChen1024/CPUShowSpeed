"""Build and run the classic-bench runner and format its results as GitHub issue submissions."""

from __future__ import annotations

import datetime as dt
import json
import shutil
import subprocess
import sys
from pathlib import Path

import click

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_DIR = REPO_ROOT / "classic-benchs"
DEFAULT_BUILD_DIR = SOURCE_DIR / "build"
DEFAULT_RESULT_DIR = REPO_ROOT / "data" / "derived" / "bench"
SCHEMA = "classic-bench-v1"
# GitHub rejects issue bodies longer than 65,536 characters.
ISSUE_BODY_LIMIT = 65536


def load_result(path: Path) -> dict:
    doc = json.loads(path.read_text())
    if doc.get("schema") != SCHEMA:
        raise click.ClickException(f"{path}: expected schema {SCHEMA}, found {doc.get('schema')!r}")
    return doc


def fmt(value: float | None, digits: int = 0) -> str:
    return "—" if value is None else f"{value:,.{digits}f}"


def warnings_for(doc: dict) -> list[str]:
    build = doc["tool"]["build"]
    settings = doc["settings"]
    notes = []
    if build["profile"] != "reference":
        notes.append(f"Custom build profile (`{build['kernel_c_flags']}`): diagnostic only, not a reference result.")
    if settings["copies"] > 1:
        notes.append(f"{settings['copies']} copies: a throughput result, not comparable with SPEC speed.")
    if not settings["pinned"]:
        notes.append("Copies were not pinned to CPUs.")
    for r in doc["results"]:
        if not r["valid"]:
            notes.append(f"`{r['benchmark']}` is invalid: {'; '.join(r['errors']) or 'no error message'}.")
    return notes


def issue_title(doc: dict) -> str:
    host = doc["host"]
    build = doc["tool"]["build"]
    return (
        f"[classic-bench] {host['cpu_model'] or host['machine']}, {build['c_compiler']} {build['c_compiler_version']}, "
        f"copies={doc['settings']['copies']}"
    )


def render_issue(doc: dict, json_name: str, limit: int = ISSUE_BODY_LIMIT) -> tuple[str, bool]:
    """Returns the Markdown issue body and whether the full JSON is embedded in it."""
    host = doc["host"]
    build = doc["tool"]["build"]
    settings = doc["settings"]
    lines = [
        "<!-- classic-bench result submission; generated by `cpushowspeed bench report`. -->",
        "## System",
        "",
        "Fill in what the JSON cannot know; leave a line empty if unknown.",
        "",
        "- System or motherboard (vendor, model):",
        "- Memory (size, type, speed, channels):",
        "- Cooling, power limits and firmware settings:",
        "- Notes:",
        "",
        "## Run",
        "",
        "| Item | Value |",
        "| --- | --- |",
        f"| CPU model | {host['cpu_model'] or '—'} |",
        f"| Logical CPUs | {host['logical_cpus']} |",
        f"| OS | {host['os']} {host['release']} ({host['machine']}) |",
        f"| C compiler | {build['c_compiler']} {build['c_compiler_version']} |",
        f"| Kernel flags | `{build['kernel_c_flags']}` ({build['profile']} profile, {build['kernel_c_dialect']}) |",
        f"| Runner | {doc['tool']['name']} {doc['tool']['version']} |",
        f"| Copies | {settings['copies']} ({'pinned to ' + ','.join(map(str, settings['cpus'])) if settings['pinned'] else 'unpinned'}) |",
        f"| Duration / warm-up / interval | {settings['duration_s']:g} s / {settings['warmup_s']:g} s / {settings['interval_s']:g} s |",
        f"| Started (UTC) | {doc['results'][0]['start_utc'] if doc['results'] else '—'} |",
        "",
        "## Results",
        "",
        "| Benchmark | Unit | Score | Interval median | Interval min | Interval max | Mean MHz | Check |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for r in doc["results"]:
        iv = r["intervals"]
        lines.append(
            f"| `{r['benchmark']}` | {r['unit']} | {fmt(r['aggregate_score'])} | {fmt(iv.get('median'))} | "
            f"{fmt(iv.get('minimum'))} | {fmt(iv.get('maximum'))} | {fmt(r['frequency']['mean_mhz'])} | "
            f"{'passed' if r['valid'] else '**failed**'} |"
        )
    notes = warnings_for(doc)
    if notes:
        lines += ["", "## Warnings", ""] + [f"- {n}" for n in notes]
    lines += ["", "## Raw result", ""]
    head = "\n".join(lines)
    payload = json.dumps(doc, separators=(",", ":"), ensure_ascii=False)
    embedded = "\n".join(
        [head, f"<details><summary><code>{json_name}</code></summary>", "", "```json", payload, "```", "", "</details>", ""]
    )
    if len(embedded) <= limit:
        return embedded, True
    note = f"The JSON ({len(payload):,} characters) exceeds GitHub's issue size limit; " f"`{json_name}.gz` is attached instead."
    return "\n".join([head, note, ""]), False


@click.group("bench")
def bench() -> None:
    """Classical benchmark runner (Dhrystone, Whetstone, LINPACK n=100)."""


@bench.command("build")
@click.option("--build-dir", type=click.Path(path_type=Path), default=DEFAULT_BUILD_DIR, show_default=True)
@click.option("--profile", type=click.Choice(["reference", "custom"]), default="reference", show_default=True)
@click.option("--kernel-flags", help="Kernel C flags; required with --profile custom.")
def build_command(build_dir: Path, profile: str, kernel_flags: str | None) -> None:
    """Configure and build classic-bench with CMake; the compiler comes from CC/CXX."""
    if (profile == "custom") != (kernel_flags is not None):
        raise click.UsageError("--kernel-flags is required with, and only with, --profile custom")
    configure = ["cmake", "-S", str(SOURCE_DIR), "-B", str(build_dir), f"-DCB_PROFILE={profile}"]
    if kernel_flags is not None:
        configure.append(f"-DCB_KERNEL_FLAGS={kernel_flags}")
    if shutil.which("ninja") and not (build_dir / "CMakeCache.txt").exists():
        configure += ["-G", "Ninja"]
    for cmd in (configure, ["cmake", "--build", str(build_dir)]):
        click.echo("+ " + " ".join(cmd), err=True)
        if subprocess.run(cmd, stdout=sys.stderr).returncode != 0:
            raise click.ClickException("build failed")
    click.echo(str(build_dir / "classic-bench"))


@bench.command("run", context_settings={"ignore_unknown_options": True, "allow_interspersed_args": False})
@click.option("--build-dir", type=click.Path(path_type=Path), default=DEFAULT_BUILD_DIR, show_default=True)
@click.option(
    "--output",
    type=click.Path(path_type=Path),
    help=f"Result file [default: {DEFAULT_RESULT_DIR.relative_to(REPO_ROOT)}/<UTC time>.json].",
)
@click.argument("runner_args", nargs=-1, type=click.UNPROCESSED)
def run_command(build_dir: Path, output: Path | None, runner_args: tuple[str, ...]) -> None:
    """Run classic-bench with RUNNER_ARGS (see `classic-bench --help`) and save its JSON.

    Prints the result path. Exits with the runner's status; invalid results are still saved.
    """
    exe = build_dir / "classic-bench"
    if not exe.exists():
        raise click.ClickException(f"{exe} not found; run `cpushowspeed bench build` first")
    proc = subprocess.run([str(exe), *runner_args], stdout=subprocess.PIPE)
    if proc.returncode == 2 or not proc.stdout:
        sys.exit(proc.returncode or 1)
    if output is None:
        output = DEFAULT_RESULT_DIR / (dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ") + ".json")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(proc.stdout)
    click.echo(str(output))
    sys.exit(proc.returncode)


@bench.command("report")
@click.argument("result", type=click.Path(exists=True, dir_okay=False, path_type=Path))
def report_command(result: Path) -> None:
    """Print RESULT as a Markdown GitHub issue body with the JSON embedded.

    When the JSON does not fit in an issue, the body says so and the result must be attached as RESULT.gz.
    """
    doc = load_result(result)
    body, embedded = render_issue(doc, result.name)
    click.echo(body, nl=False)
    click.echo(f"Suggested title: {issue_title(doc)}", err=True)
    if not embedded:
        click.echo(f"JSON too large to embed; attach the output of `gzip -k {result}`.", err=True)
